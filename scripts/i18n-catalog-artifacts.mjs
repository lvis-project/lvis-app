/**
 * i18n catalog assembler — the pure half.
 *
 * Builds the barrel file contents in memory and returns them. Nothing here
 * touches the working tree, so the same function can answer two different
 * questions: `i18n-build-catalog.mjs` writes the result, and
 * `check-i18n-catalog-barrels.mjs` compares it against the committed bytes.
 * One authority for what a barrel should contain, rather than a writer and a
 * checker that each re-derive it and drift apart.
 *
 * The barrels only re-export and spread the per-surface fragments in this
 * directory; they hold no text of their own. Fragment order is therefore the
 * whole of what this produces, and it comes from `Array.prototype.sort` with
 * no comparator — UTF-16 code-unit order, which is fixed by the language spec
 * and identical on every platform. `readdirSync` order is not, which is
 * exactly why the sort is not optional.
 */
import { readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));

/** Default location of the catalog sources: `src/i18n/messages`. */
export const MESSAGES_DIR = join(HERE, "..", "src", "i18n", "messages");

/** Fragment name → a safe JS identifier suffix. */
function sanitize(name) {
  let id = name.replace(/[^A-Za-z0-9_]/g, "_");
  if (/^[0-9]/.test(id)) id = `_${id}`;
  return id;
}

/**
 * Assemble both barrels from the fragments under `<messagesDir>/generated`.
 *
 * @param {string} [messagesDir] Root of the message catalogs.
 * @returns {{ fragments: string[], artifacts: { path: string, content: string }[] }}
 *   `path` is absolute; `content` is the exact bytes the barrel should hold.
 */
export function buildI18nCatalogArtifacts(messagesDir = MESSAGES_DIR) {
  const genDir = join(messagesDir, "generated");
  const generatedLocalesDir = join(messagesDir, "generated-locales");

  const fragments = readdirSync(genDir)
    .filter((f) => f.endsWith(".ts") && f !== "index.ts")
    .map((f) => f.slice(0, -3))
    .sort();

  const enImportLines = fragments
    .map((ns) => `import { en as en_${sanitize(ns)} } from "./${ns}.js";`)
    .join("\n");
  const koImportLines = fragments
    .map((ns) => `import { ko as ko_${sanitize(ns)} } from "../generated/${ns}.js";`)
    .join("\n");

  const enSpread = fragments.map((ns) => `  ...en_${sanitize(ns)},`).join("\n");
  const koSpread = fragments.map((ns) => `  ...ko_${sanitize(ns)},`).join("\n");

  const englishBody = `/**
 * AUTO-GENERATED barrel — do not edit by hand.
 *
 * Regenerated by \`scripts/i18n-build-catalog.mjs\`, which globs the per-surface
 * fragment files in this directory (\`<namespace>.ts\`, each exporting \`en\`/\`ko\`
 * objects) and merges the English default catalog here. Non-English generated
 * catalogs are language-pack chunks under \`../generated-locales/\`.
 *
 * Fragments: ${fragments.length}
 */
${enImportLines ? enImportLines + "\n" : ""}
export const generatedEn: Record<string, string> = {
${enSpread}
};
`;

  const koreanBody = `/** AUTO-GENERATED by scripts/i18n-build-catalog.mjs. */
${koImportLines ? koImportLines + "\n" : ""}
export const koMessages: Record<string, string> = {
${koSpread}
};
`;

  return {
    fragments,
    artifacts: [
      { path: join(genDir, "index.ts"), content: englishBody },
      { path: join(generatedLocalesDir, "ko.ts"), content: koreanBody },
    ],
  };
}
